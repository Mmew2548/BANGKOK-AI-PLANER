_THAI = re.compile(r"[ก-ฮ0-9a-z]")


def _key(s):
    """คีย์เทียบชื่อสถานี: เก็บเฉพาะพยัญชนะไทย/ตัวเลข/อังกฤษ (ตัดสระ วรรณยุกต์ ช่องว่าง)
    เพราะชื่อในไฟล์ PDF ตกหล่นสระ/วรรณยุกต์บางตัว"""
    s = str(s or "").lower()
    s = re.sub(r"สถานี|รถไฟฟ้า|\bbts\b|\bmrt\b|station", " ", s)
    return "".join(_THAI.findall(s))


def _build_keys():
    d = {}
    for sysname, rows in (("BTS", BTS_NAMES), ("PINK", PINK_NAMES), ("YELLOW", YELLOW_NAMES)):
        d[sysname] = [(code, [_key(th), _key(en)]) for code, th, en in rows]
    d["RED"] = [(th, [_key(a) for a in alts]) for th, alts in RED_NAMES]
    for k in d:
        d[k] = [(c, [x for x in ks if x]) for c, ks in d[k]]
    return d


_NAME_KEYS = _build_keys()


def station_code(system, name):
    """หารหัสสถานีจากชื่อที่ Google ส่งมา (ไทยหรืออังกฤษ) คืน None ถ้าไม่พบ
    ใช้การเทียบเท่าก่อน แล้วค่อยหาคีย์ที่ยาวที่สุดที่อยู่ในชื่อ (ลาดพร้าว 71 ชนะ ลาดพร้าว)"""
    sysname = resolve_system(system) or str(system).upper()
    k = _key(name)
    if not k or sysname not in _NAME_KEYS:
        return None
    best, best_len = None, 0
    for code, keys in _NAME_KEYS[sysname]:
        for kk in keys:
            if k == kk:
                return code
            if kk in k and len(kk) > best_len:
                best, best_len = code, len(kk)
    return best


