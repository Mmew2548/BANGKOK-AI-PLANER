def matrix_fare(system, origin, dest):
    """ราคาจากเมทริกซ์ตามรหัสสถานี เช่น matrix_fare("BTS", "N8", "E4"), ("PINK","PK01","MT02")
    system: BTS | PINK | YELLOW | RED  (BTS ใช้ "N6" แทน N6*) คืน None ถ้าไม่พบสถานี"""
    idx, m = _MATRICES[resolve_system(system) or str(system).upper()]
    if origin not in idx or dest not in idx:
        return None
    return m[idx[origin]][idx[dest]]


