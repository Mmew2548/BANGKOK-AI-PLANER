def resolve_system(name):
    """แปลงชื่อสายจากที่ไหนก็ได้ ("Blue Line", "MRT Pink Line", "สายสีทอง") เป็นรหัสมาตรฐาน
    คืน None ถ้าไม่รู้จัก (PURPLE รู้จักแต่ไม่มีตารางราคา)"""
    n = str(name or "").strip().lower()
    if not n:
        return None
    if n in ("blue", "pink", "yellow", "red", "gold", "brt", "arl", "bts", "purple"):
        return n.upper()
    for key, words in _ALIASES:
        if any(w in n for w in words):
            return key
    return None


def transit_fare(system, stops, elderly=False):
    """ราคาแบบนับสถานี: BLUE, ARL, GOLD, BRT คืน None ถ้าไม่รู้จักสาย
    (BTS/ชมพู/เหลือง/แดง ใช้ fare_by_names หรือ matrix_fare)"""
    s = resolve_system(system)
    if s == "GOLD":
        return GOLD_FARE
    if s == "BRT":
        return BRT_FARE
    if s == "BLUE":
        return table_fare(BLUE_ELDERLY if elderly else BLUE, stops)
    if s == "ARL":
        return table_fare(ARL, stops)
    return None


def fare_by_names(system, dep_name, arr_name, stops):
    """ตัวเดียวจบ: รับชื่อสายและชื่อสถานีขึ้น/ลงจาก Google คืนราคา หรือ None ถ้าหาไม่ได้"""
    s = resolve_system(system)
    if s in ("BTS", "PINK", "YELLOW", "RED"):
        a, b = station_code(s, dep_name), station_code(s, arr_name)
        return matrix_fare(s, a, b) if a and b else None
    return transit_fare(s, stops) if s else None


# แท็กซี่มิเตอร์ ตามประกาศกรมการขนส่งทางบก (ราชกิจจานุเบกษา): (ถึงกม.ที่, บาท/กม.)
TAXI_START = 35.0                      # 1 กม.แรก
TAXI_STEPS = [(10, 6.5), (20, 7.0), (40, 8.0), (60, 8.5), (80, 9.0), (10**6, 10.5)]
TAXI_SLOW_PER_MIN = 3.0                # รถติด/ความเร็ว < 6 กม./ชม.
TAXI_AIRPORT_SURCHARGE = 50.0          # ค่าบริการสนามบิน (ไม่ใช่ค่ามิเตอร์)

def taxi_fare(km, jam_minutes=0.0, airport=False):
    fare, prev = TAXI_START, 1.0
    for upto, rate in TAXI_STEPS:
        if km <= prev:
            break
        fare += (min(km, upto) - prev) * rate
        prev = upto
    fare += jam_minutes * TAXI_SLOW_PER_MIN
    if airport:
        fare += TAXI_AIRPORT_SURCHARGE
    return round(fare)

# มอเตอร์ไซค์รับจ้าง (วิน) ไม่มีราคากลางในราชกิจจาฯ -- เป็นค่าประมาณ แก้ได้
def motorcycle_fare(km):
    if km <= 2:
        return 25
    if km <= 15:
        return round(25 + (min(km, 5) - 2) * 5 + max(0, km - 5) * 10)
    return round(km * 10)
